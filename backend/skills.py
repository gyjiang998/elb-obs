def _materialize_skill_manifest(manifest: dict[str, Any]) -> dict[str, Any]:
    profile = SKILL_GOVERNANCE_PROFILES[manifest["skill_id"]]
    materialized = deepcopy(manifest)
    evaluation = deepcopy(profile["evaluation"])
    evaluation["golden_fixture"] = manifest["fixture"]
    materialized.update(
        {
            "skill_contract_version": SKILL_EVOLUTION_CONTRACT_VERSION,
            "skill_class": profile["skill_class"],
            "claim_boundary": profile["claim_boundary"],
            "required_evidence": deepcopy(profile["required_evidence"]),
            "quality_gates": deepcopy(profile["quality_gates"]),
            "evaluation": evaluation,
            "change_control": deepcopy(SKILL_CHANGE_CONTROL),
            "evolution": {
                "recording": "versioned_registry + immutable_artifact_or_transcript + regression_suite",
                "event_ids": list(profile["evolution_events"]),
                "events": [deepcopy(SKILL_EVOLUTION_EVENTS[event_id]) for event_id in profile["evolution_events"]],
            },
        }
    )
    return materialized


def validate_skill_registry() -> list[str]:
    """Return registry defects so CI and service startup reject partial governance."""

    errors: list[str] = []
    manifest_ids = [str(manifest.get("skill_id", "")) for manifest in SKILL_MANIFESTS]
    if len(manifest_ids) != len(set(manifest_ids)):
        errors.append("skill_id must be unique")
    missing_profiles = sorted(set(manifest_ids) - set(SKILL_GOVERNANCE_PROFILES))
    extra_profiles = sorted(set(SKILL_GOVERNANCE_PROFILES) - set(manifest_ids))
    if missing_profiles:
        errors.append(f"missing governance profiles: {', '.join(missing_profiles)}")
    if extra_profiles:
        errors.append(f"orphan governance profiles: {', '.join(extra_profiles)}")
    for manifest in SKILL_MANIFESTS:
        skill_id = str(manifest.get("skill_id", ""))
        if not skill_id or not manifest.get("version"):
            errors.append(f"{skill_id or '<missing>'}: id and version are required")
            continue
        profile = SKILL_GOVERNANCE_PROFILES.get(skill_id)
        if not profile:
            continue
        if not profile["claim_boundary"] or not profile["required_evidence"]:
            errors.append(f"{skill_id}: claim boundary and required evidence are required")
        if not profile["quality_gates"]:
            errors.append(f"{skill_id}: at least one quality gate is required")
        evaluation = profile["evaluation"]
        if not evaluation["semantic_assertions"] or not evaluation["failure_scenarios"]:
            errors.append(f"{skill_id}: semantic assertions and failure scenarios are required")
        if not manifest.get("fixture"):
            errors.append(f"{skill_id}: golden fixture is required")
    return errors


def action_catalog() -> list[dict[str, Any]]:
    return PAGE_ACTIONS


def skill_catalog() -> list[dict[str, Any]]:
    errors = validate_skill_registry()
    if errors:
        raise RuntimeError(f"Invalid skill registry: {'; '.join(errors)}")
    return [_materialize_skill_manifest(manifest) for manifest in SKILL_MANIFESTS]


def registered_action(action_id: str) -> dict[str, Any]:
    for action in PAGE_ACTIONS:
        if action["action_id"] == action_id:
            return action
    raise PlatformError("ACTION_NOT_REGISTERED", "Page action is not registered.", status_code=404, details={"action_id": action_id})
